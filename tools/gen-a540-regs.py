#!/usr/bin/env python3
"""Generate platforms/sagit/gpu/NativeAdrenoA540Regs.h from the official Mesa a5xx.xml.

Provenance: mesa/mesa @ main, src/freedreno/registers/adreno/a5xx.xml
(Adreno 530/540 = A5XX family; offsets in the XML are already dword offsets,
matching the style of NativeAdreno's generated A740 header).

Usage:
    python tools/gen-a540-regs.py <a5xx.xml> <out.h>
"""
import re
import sys

# Registers the A740 header needs, plus the A5XX power/clock/CP set.
WANTED = [
    # RBBM / power / clocks
    "RBBM_POWER_CNTL", "RBBM_POWER_STATUS", "RBBM_STATUS", "RBBM_STATUS2",
    "RBBM_STATUS3", "RBBM_INT_0_MASK", "RBBM_INT_0_STATUS",
    "RBBM_INT_CLEAR_CMD", "RBBM_INTERFACE_HANG_INT_CNTL",
    "RBBM_CLOCK_CNTL", "RBBM_CLOCK_CNTL2", "RBBM_CLOCK_STATUS",
    "RBBM_CLOCK_HYST", "RBBM_CLOCK_DELAY", "RBBM_CLOCK_CNTL_UCHE",
    "RBBM_CLOCK_CNTL2_UCHE", "RBBM_CLOCK_HYST_UCHE", "RBBM_CLOCK_DELAY_UCHE",
    "RBBM_CLOCK_CNTL_RB0", "RBBM_CLOCK_CNTL2_RB0", "RBBM_CLOCK_CNTL_CCU0",
    "RBBM_CLOCK_HYST_RB_CCU0", "RBBM_CLOCK_CNTL_RAC", "RBBM_CLOCK_CNTL2_RAC",
    "RBBM_CLOCK_DELAY_RAC", "RBBM_CLOCK_HYST_RAC",
    "RBBM_CLOCK_CNTL_TSE_RAS_RBBM", "RBBM_CLOCK_MODE_GPC",
    "RBBM_CLOCK_MODE_VFD", "RBBM_CLOCK_HYST_GPC", "RBBM_CLOCK_HYST_VFD",
    "RBBM_CLOCK_DELAY_GPC", "RBBM_CLOCK_DELAY_VFD", "RBBM_CLOCK_MODE_HLSQ",
    "RBBM_CLOCK_DELAY_HLSQ", "RBBM_CLOCK_HYST_HLSQ", "RBBM_CLOCK_MODE_CP",
    "RBBM_NC_MODE_CNTL", "RBBM_SECVID_TSB_CNTL", "RBBM_SECVID_TSB_TRUSTED_BASE",
    "RBBM_SECVID_TSB_TRUSTED_SIZE", "RBBM_SECVID_TRUST_CNTL",
    "RBBM_PERFCTR_CNTL", "RBBM_PERFCTR_GPU_BUSY_MASKED", "RBBM_ISDB_CNT",
    "RBBM_RAC_THRESHOLD_CNT", "RBBM_SP_HYST_CNT",
    # CP
    "CP_RB_BASE", "CP_RB_BASE_HI", "CP_RB_CNTL", "CP_RB_RPTR_ADDR",
    "CP_RB_RPTR", "CP_RB_WPTR", "CP_RB_WPTR_DELAY", "CP_SQE_CNTL",
    "CP_SQE_INSTR_BASE", "CP_ME_INIT", "CP_ME_CNTL", "CP_ME_STATUS",
    "CP_PFP_INSTR_BASE", "CP_PFP_CNTL", "CP_HW_FAULT",
    "CP_INTERRUPT_STATUS", "CP_INT_CNTL", "CP_INT_STATUS",
    "CP_SCRATCH_REG0", "CP_SCRATCH_REG1", "CP_SCRATCH_REG2",
    "CP_SCRATCH_REG3", "CP_SCRATCH_REG4", "CP_SCRATCH_REG5",
    "CP_SCRATCH_REG6", "CP_SCRATCH_REG7", "CP_ALWAYS_ON_COUNTER",
    "CP_AHB_CNTL", "CP_APERTURE_CNTL_HOST", "CP_APERTURE_CNTL_CDMM",
    "CP_PROTECT_CNTL", "CP_PROTECT_STATUS", "CP_PROTECT",
    "CP_SQE_STAT_ADDR", "CP_SQE_STAT_DATA", "CP_PERFCTR_CP_SEL_0",
    # UCHE
    "UCHE_MODE_CNTL", "UCHE_TRAP_BASE", "UCHE_WRITE_THRU_BASE",
    "UCHE_GMEM_RANGE_MIN", "UCHE_GMEM_RANGE_MAX", "UCHE_CACHE_WAYS",
    "UCHE_CLIENT_PF", "UCHE_GBIF_GX_CONFIG", "UCHE_CMDQ_CONFIG",
    "UCHE_INVALIDATE0", "UCHE_INVALIDATE1", "UCHE_STATIC_OFFSET",
    "UCHE_FLUSH_CTRL", "UCHE_FLUSH_STATUS",
    # DB / RB / GRAS / TPL1 / SP / HLSQ / VSC / VFD / VPC / TSE
    "RB_NC_MODE_CNTL", "RB_CMP_DBG_ECO_CNTL", "RB_MODECNTL", "RB_DEPTH_CNTL",
    "GRAS_NC_MODE_CNTL", "TPL1_NC_MODE_CNTL", "SP_NC_MODE_CNTL",
    "HLSQ_NC_MODE_CNTL", "VSC_NC_MODE_CNTL",
    # GBIF
    "GBIF_HALT", "GBIF_HALT_ACK",
]

ROW = re.compile(r'<reg32\s+offset="(0x[0-9a-fA-F]+)"\s+name="([A-Z0-9_]+)"')


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    srcs, out = sys.argv[1:-1], sys.argv[-1]
    xml = ""
    for s in srcs:
        with open(s, encoding="utf-8") as f:
            xml += f.read()
    regs = {}
    for off, name in ROW.findall(xml):
        # first definition wins; A5XX has per-context duplicates in some blocks
        regs.setdefault(name, int(off, 16))

    lines = []
    missing = []
    lines.append("/* SPDX-License-Identifier: MIT */")
    lines.append("#ifndef NATIVE_ADRENO_A540_REGS_H")
    lines.append("#define NATIVE_ADRENO_A540_REGS_H")
    lines.append("#include <stdint.h>")
    lines.append("/*")
    lines.append(" * Adreno 540 (A5XX) register offsets, in dwords.")
    lines.append(" *")
    lines.append(" * Generated by tools/gen-a540-regs.py from the official Mesa register")
    lines.append(" * database: mesa/mesa @ main, src/freedreno/registers/adreno/a5xx.xml")
    lines.append(" * (the XML offsets are already dword offsets, same convention as the")
    lines.append(" * generated A740 header in this tree).")
    lines.append(" *")
    lines.append(" * Status: REGISTER MAP ONLY. Nothing here has been executed on hardware yet.")
    lines.append(" * A540 = A5XX family, which has *no GMU*: power/clock control goes through")
    lines.append(" * RBBM_POWER_CNTL + RBBM_CLOCK_* and the SMMU is a Qualcomm SMMUv1 outside")
    lines.append(" * the GPU register space, so the A740 GMU/SMMU-context code cannot be reused.")
    lines.append(" */")
    for name in WANTED:
        if name in regs:
            lines.append("#define A540_%-40s 0x%05x" % (name, regs[name]))
        else:
            missing.append(name)
    lines.append("")
    lines.append("#define A540_REG_COUNT %d" % (len(WANTED) - len(missing)))
    lines.append("")
    lines.append("/* Simple-framebuffer window used for early scanout on sagit (from the")
    lines.append(" * edk2 MSM8998 memory map: Display Reserved 0x9D400000+0x02400000). */")
    lines.append("#define A540_SAGIT_FB_BASE   0x9d400000u")
    lines.append("#define A540_SAGIT_FB_SIZE   0x02400000u")
    lines.append("#define A540_SAGIT_FB_WIDTH  1080u")
    lines.append("#define A540_SAGIT_FB_HEIGHT 1920u")
    lines.append("#define A540_SAGIT_FB_STRIDE 4320u /* 1080 * 4 */")
    lines.append("#endif")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d defines (%d wanted names absent in A5XX)"
          % (out, len(WANTED) - len(missing), len(missing)))
    if missing:
        print("absent:", ", ".join(missing))


if __name__ == "__main__":
    main()


